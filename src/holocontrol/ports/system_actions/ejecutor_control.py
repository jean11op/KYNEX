from typing import Protocol


class EjecutorControl(Protocol):

    """ Compatible estructuralmente con EjecutorAccionesWindows existente.
        pausar/detener deben liberar botones y teclas si se añade arrastre en el futuro.
        Las operaciones de ciclo de vida deben ser idempotentes. Las excepciones
        deben propagarse; no ocultar errores de hardware ni de seguridad.
    """
    def activar(self) -> None: ...
    def pausar(self) -> None: ...
    def detener(self) -> None: ...
    def establecer_mano_detectada(self, detectado: bool) -> None: ...
    def mover_cursor(self, x: int, y: int) -> None: ...
    def clic_izquierdo(self) -> None: ...
    def clic_derecho(self) -> None: ...
    def iniciar_arrastre(self, x: int, y: int) -> None: ...
    def ajustar_zoom(self, cantidad: int) -> None: ...
    def alternar_dictado(self) -> None: ...
    def pulsar_tecla(self, tecla: str) -> None: ...
    def minimizar_ventana(self) -> None: ...
    def iniciar_cambio_ventana(self, x: float) -> None: ...
    def actualizar_cambio_ventana(self, x: float) -> None: ...
    def terminar_cambio_ventana(self, cancelado: bool = False) -> None: ...
    def desplazar(self, cantidad: float) -> None: ...
